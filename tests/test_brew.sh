#!/usr/bin/env bash
# test_brew.sh — Homebrew capture/restore tests using mock-brew.
set -uo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib.sh
# shellcheck disable=SC1091
source "${REPO_ROOT}/tests/lib.sh"

CAPTURE="${REPO_ROOT}/apps/brew/capture.sh"
RESTORE="${REPO_ROOT}/apps/brew/restore.sh"
NORM="${REPO_ROOT}/apps/brew/normalize.py"

t_title "homebrew inventory"

t_setup
BREW_DIR="$ATOMIC_WS_ROOT/apps/brew/inventory/${WORKSTATION_PROFILE}"
rm -rf "$BREW_DIR"
mkdir -p "$MOCK_STATE/brew"

t_case "capture skips cleanly when brew is absent"
t_disable_mock brew
out=$(bash "$CAPTURE" 2>&1)
assert_contains "skip message" "Homebrew is not installed" "$out"
t_enable_mock brew

t_case "capture dumps a sorted Brewfile and a leaves list"
printf 'ripgrep\n' >"$MOCK_STATE/brew/formulae.txt"
printf 'starship\n' >"$MOCK_STATE/brew/leaves.txt"
bash "$CAPTURE" >/dev/null 2>&1
assert_contains "formula line" 'brew "ripgrep"' "$BREW_DIR/Brewfile"
assert_contains "header explains generation" "Generated by" "$BREW_DIR/Brewfile"
assert_contains "leaves file" "starship" "$BREW_DIR/leaves.${WORKSTATION_PROFILE}.txt"

t_case "capture does not mirror flatpak apps into the Brewfile"
printf 'ripgrep\n' >"$MOCK_STATE/brew/formulae.txt"
printf 'starship\n' >"$MOCK_STATE/brew/leaves.txt"
printf 'org.mozilla.firefox\n' >"$MOCK_STATE/brew/flatpaks.txt"
bash "$CAPTURE" >/dev/null 2>&1
assert_not_contains "flatpak line dropped" 'flatpak "org.mozilla.firefox"' "$BREW_DIR/Brewfile"
assert_contains "formula still captured" 'brew "ripgrep"' "$BREW_DIR/Brewfile"

t_case "restore without a Brewfile warns and exits 0"
rm -rf "$BREW_DIR"
out=$(bash "$RESTORE" 2>&1)
assert_rc 0 "restore-without-file exits 0"
assert_contains "missing-Brewfile warning" "no Brewfile" "$out"

t_case "restore installs missing formulae (additive)"
printf 'ripgrep\nstarship\njq\n' >"$MOCK_STATE/brew/formulae.txt"
printf 'starship\n' >"$MOCK_STATE/brew/leaves.txt"
bash "$CAPTURE" >/dev/null 2>&1
# wipe installed state, keep the Brewfile
printf 'jq\n' >"$MOCK_STATE/brew/formulae.txt"
out=$(bash "$RESTORE" 2>&1)
assert_rc 0 "restore exits 0"
assert_contains "ripgrep installed" "Installed ripgrep" "$out"
assert_contains "starship installed" "Installed starship" "$out"

t_case "restore is idempotent — nothing new on second run"
out=$(bash "$RESTORE" 2>&1)
assert_not_contains "no new installs" "Installed " "$out"

t_case "restore failure (bad formula) reports and exits non-zero"
printf 'brew "failme-bad"\n' >>"$BREW_DIR/Brewfile"
out=$(bash "$RESTORE" 2>&1)
assert_rc 1 "restore failure exits 1"
assert_contains "error reported" "failme-bad" "$out"

t_case "restore skips cleanly when brew is absent"
t_disable_mock brew
out=$(bash "$RESTORE" 2>&1)
assert_contains "skip message" "Homebrew is not installed" "$out"
t_enable_mock brew

t_case "normalize.py imports cleanly; every function still has a caller"
if python3 - "$NORM" <<'PYEOF'
import ast, importlib.util, sys
path = sys.argv[1]
spec = importlib.util.spec_from_file_location("aw_normalize_probe", path)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
required = ["ENTRY", "TITLES", "ORDER", "HEADER", "read_leaves", "group", "render", "main"]
missing = [n for n in required if not hasattr(mod, n)]
if missing:
    raise SystemExit("missing public names: " + ",".join(missing))
tree = ast.parse(open(path, encoding="utf-8").read())
loads = [n.id for n in ast.walk(tree)
         if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)]
dead = [n.name for n in tree.body
        if isinstance(n, ast.FunctionDef) and n.name not in loads]
if dead:
    raise SystemExit("dead functions: " + ",".join(dead))
PYEOF
then
    t_ok
else
    t_fail "normalize.py import/caller probe failed"
fi

t_case "Brewfile output schema unchanged"
assert_contains "generated header" "Generated by" "$BREW_DIR/Brewfile"
assert_contains "formula directive" 'brew "ripgrep"' "$BREW_DIR/Brewfile"

t_teardown
rm -rf "${REPO_ROOT}/apps/brew/inventory/testbox"

printf '\nbrew: %d checks, %d failed\n' "$TESTS_RUN" "$TESTS_FAILED" >&2
exit "$TESTS_FAILED"
