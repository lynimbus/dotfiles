#!/usr/bin/env python3
"""normalize.py — turn a raw `brew bundle dump` into the committed Brewfile.

`brew bundle dump` writes a description comment BEFORE the entry it describes,
and mixes several managers into one file (brew/cask/tap plus whatever other
managers the user has: flatpak, vscode, mas). The flatpak bucket is dropped
rather than grouped — apps/flatpak/inventory/<profile>.json is the single
authoritative list for flatpak state. Sorting that file line-by-line
(what a plain `grep '^brew ' | sort` does) detaches every description into a
floating comment block and buries the foreign entries in a "rest" bucket.

This module keeps each comment block attached to its entry, groups the entries
by manager, sorts inside each group (LC_ALL=C, i.e. byte order) and prints the
result with one heading per manager.

Usage: normalize.py RAW_DUMP LEAVES_FILE PROFILE

`leaves` is the output of `brew leaves`; a formula that is not in it was pulled
in as a dependency and gets the `# auto (dependency)` marker.
"""

from __future__ import annotations

import re
import sys

ENTRY = re.compile(r'^(tap|brew|cask|flatpak|vscode|mas)\s+"([^"]*)"')

TITLES = {
    "tap": "taps",
    "brew": "formulae",
    "cask": "casks",
    # never emitted: group() drops flatpak entries (see apps/flatpak/inventory/),
    "vscode": "vscode extensions",
    "mas": "mac app store (not installable on Linux)",
    "other": "other brew bundle directives",
}
ORDER = ["tap", "brew", "cask", "vscode", "mas", "other"]

HEADER = """\
# Brewfile — atomic-workstation (profile: {profile})
#
# Generated by apps/brew/capture.sh — do not edit by hand, re-run capture.
# Formula lines marked 'auto' are dependencies that brew bundle dump
# picked up; they are not packages you requested yourself (see the
# leaves file next to this Brewfile). brew bundle installs everything
# listed here on a fresh machine."""


def read_leaves(path: str) -> set[str]:
    try:
        with open(path, encoding="utf-8") as fh:
            return {line.strip() for line in fh if line.strip()}
    except FileNotFoundError:
        return set()


def group(raw_path: str, leaves: set[str]) -> tuple[dict[str, list], list[str]]:
    """Return {manager: [(sort_key, lines)]} plus any trailing stray comments."""
    groups: dict[str, list[tuple[str, list[str]]]] = {}
    pending: list[str] = []

    with open(raw_path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                pending.append(line)
                continue

            match = ENTRY.match(line)
            if not match:
                groups.setdefault("other", []).append((line, pending + [line]))
                pending = []
                continue

            manager, name = match.group(1), match.group(2)
            if manager == "flatpak":
                # One package, one owner: `brew bundle dump` mirrors every
                # flatpak app it can see, which put a second copy of the whole
                # flatpak list in this file — including stale entries that
                # apps/flatpak/inventory.py deliberately skips. Flatpak state
                # lives in apps/flatpak/inventory/<profile>.json only.
                pending = []
                continue
            entry = line
            if manager == "brew" and name not in leaves:
                entry += " # auto (dependency)"
            groups.setdefault(manager, []).append((name, pending + [entry]))
            pending = []

    return groups, pending


def render(groups: dict[str, list], trailing: list[str], profile: str) -> str:
    out = [HEADER.format(profile=profile)]
    for manager in ORDER:
        entries = groups.get(manager)
        if not entries:
            continue
        out += ["", f"# ── {TITLES[manager]} ──"]
        for _key, lines in sorted(entries, key=lambda item: item[0]):
            out += lines
    if trailing:
        out += trailing
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 4:
        sys.exit("usage: normalize.py RAW_DUMP LEAVES_FILE PROFILE")
    raw_path, leaves_path, profile = argv[1:]
    groups, trailing = group(raw_path, read_leaves(leaves_path))
    sys.stdout.write(render(groups, trailing, profile) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
